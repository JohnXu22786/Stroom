import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:stroom/pages/anki_page.dart';
import 'package:stroom/anki/apkg/apkg_result.dart';
import 'package:stroom/l10n/app_localizations_en.dart';
import 'package:stroom/l10n/app_localizations_zh.dart';
import 'package:stroom/anki/pages/anki_stats_page.dart';
import 'package:stroom/anki/providers/anki_provider.dart';
import 'package:stroom/anki/sync/anki_incremental_sync.dart';
import 'package:stroom/anki/sync/anki_sync_protocol_client.dart';
import 'package:stroom/l10n/app_localizations.dart';

void main() {
  test('formats apkg import counts in the active locale', () {
    final english = AppLocalizationsEn();
    final chinese = AppLocalizationsZh();
    const summary = AnkiApkgImportSummary(
      decksImported: 2,
      notesImported: 3,
      cardsImported: 4,
    );

    expect(summary.format(english), 'Imported 2 decks, 3 notes, and 4 cards');
    expect(summary.format(chinese), '导入完成：2 个牌组，3 个笔记，4 张卡片');

    const missingFile = AnkiApkgException.fileNotFound('/tmp/deck.apkg');
    expect(
      missingFile.localizedMessage(english),
      'The selected .apkg file could not be found: /tmp/deck.apkg',
    );
    expect(
      missingFile.localizedMessage(chinese),
      '找不到所选的 .apkg 文件：/tmp/deck.apkg',
    );
    expect(
      const AnkiApkgException.unexpectedError('/tmp/deck.apkg')
          .localizedMessage(english),
      'The .apkg operation failed while accessing this path: /tmp/deck.apkg',
    );
    expect(
      const AnkiApkgException.unexpectedError('/tmp/deck.apkg')
          .localizedMessage(chinese),
      '.apkg 操作访问此路径时失败：/tmp/deck.apkg',
    );
    expect(
      const AnkiApkgException.exportFailed('/tmp/collection.anki2')
          .localizedMessage(english),
      'The Anki deck could not be packaged from this database: /tmp/collection.anki2',
    );
    expect(
      english.backupRestoreApkgOperationFailed,
      'The .apkg operation failed because the file or database could not be read.',
    );
  });

  test('localizes failures generated by incremental sync', () {
    const error = AnkiSyncException.appGenerated('同步服务器 chunk 响应无法解析');

    expect(
      error.localizedMessage(AppLocalizationsEn()),
      'Incremental sync could not complete. Check the server and connection, then try again.',
    );
    expect(
      error.localizedMessage(AppLocalizationsZh()),
      '增量同步未能完成。请检查服务器和网络连接后重试。',
    );
    expect(
      AppLocalizationsEn().ankiWebSyncUnsupportedPlatform,
      'Sign in to AnkiWeb to sync on web. Open Anki settings with the cloud icon to log in.',
    );
    expect(
      AppLocalizationsZh().ankiWebSyncUnsupportedPlatform,
      '网页端需登录 AnkiWeb 才能同步。请点击云朵图标打开 Anki 设置并登录。',
    );
    expect(
      const AnkiSyncException.appGenerated(
        '设备时间与同步服务器相差超过 5 分钟',
        failureCode: AnkiSyncFailureCode.deviceClockMismatch,
      ).localizedMessage(AppLocalizationsEn()),
      'The device clock differs from the sync server by more than 5 minutes. Correct the clock and try again.',
    );
    expect(
      const AnkiSyncFullTransferRequired.appGenerated('服务器 collection 为空')
          .localizedMessage(AppLocalizationsEn()),
      'This collection cannot be synchronized incrementally. Choose a full upload or download to continue.',
    );
    expect(
      const AnkiSyncException.appGenerated(
        '同步数据校验失败；请完整下载后重试',
        failureCode: AnkiSyncFailureCode.fullDownloadRequired,
      ).localizedMessage(AppLocalizationsEn()),
      'The sync sanity check failed and local changes were rolled back. Download the server collection in full, then try again.',
    );
    expect(
      const AnkiSyncException.appGenerated(
        '同步服务器要求更新客户端',
        failureCode: AnkiSyncFailureCode.upgradeClientRequired,
      ).localizedMessage(AppLocalizationsEn()),
      'This server requires a newer sync client.',
    );
    expect(
      const AnkiSyncException('remote diagnostic')
          .localizedMessage(AppLocalizationsEn()),
      'remote diagnostic',
    );
  });

  testWidgets('shows localized unsupported statistics state on web', (
    tester,
  ) async {
    for (final locale in const [Locale('en'), Locale('zh')]) {
      await tester.pumpWidget(
        ProviderScope(
          overrides: [
            ankiDatabaseProvider.overrideWith(
              (_) => Future.error(const AnkiStatsUnsupportedException()),
            ),
          ],
          child: MaterialApp(
            locale: locale,
            localizationsDelegates: AppLocalizations.localizationsDelegates,
            supportedLocales: AppLocalizations.supportedLocales,
            home: const AnkiStatsPage(),
          ),
        ),
      );
      await tester.pump();

      expect(
        find.text(
          locale.languageCode == 'en'
              ? 'Anki statistics are unavailable on this platform.'
              : '当前平台无法查看 Anki 统计数据。',
        ),
        findsOneWidget,
      );
      await tester.pumpWidget(const SizedBox());
    }
  });

  testWidgets('localizes the shared web database error on the deck page', (
    tester,
  ) async {
    for (final locale in const [Locale('en'), Locale('zh')]) {
      await tester.pumpWidget(
        ProviderScope(
          overrides: [
            ankiDatabaseProvider.overrideWith(
              (_) => Future.error(const AnkiStatsUnsupportedException()),
            ),
          ],
          child: MaterialApp(
            locale: locale,
            localizationsDelegates: AppLocalizations.localizationsDelegates,
            supportedLocales: AppLocalizations.supportedLocales,
            home: const AnkiDroidPage(),
          ),
        ),
      );
      await tester.pump();

      expect(
        find.text(
          locale.languageCode == 'en'
              ? 'To browse or manage decks on web, sign in to AnkiWeb using the cloud icon.'
              : '如需在网页端浏览或管理牌组，请点击云朵图标登录 AnkiWeb。',
        ),
        findsOneWidget,
      );
      await tester.pumpWidget(const SizedBox());
    }
  });
}
